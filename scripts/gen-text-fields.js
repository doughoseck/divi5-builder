#!/usr/bin/env node
/*
 * gen-text-fields.js: write plugin/divi5-builder/inc/blocks-text-fields.php, the text-bearing elements of every Divi 5
 * module, from YOUR catalog/catalog.json (node scripts/catalog.js build <Divi theme folder> makes it). Issue #32.
 *
 *   node scripts/gen-text-fields.js            # writes the PHP file
 *   node scripts/gen-text-fields.js --stdout   # prints it instead (the blocks test compares this with the committed file)
 *
 * An element is text-bearing when one of its catalogue fields has path "<element>.innerContent", is not hidden, and is
 * marked as visitor text: dynamic content of type "text" (features.dynamicContent.type, kept as `dynamic` by
 * catalog.js). Denied even then: the elements redirect, number and barProgress, the element label of
 * divi/post-filter-item, any field whose label contains URL, Link, Percent, Count, Class or ID, and any field whose
 * editor is divi/code (code, not words), divi/map (an address for the geocoder) or divi/textarea (the contact form's
 * e-mail message pattern, never shown on the page).
 * The plugin adds its own hand list (in inc/blocks.php) for text the catalogue does not mark (the blurb title, ...).
 * The output is sorted, so the same catalogue always gives the same bytes.
 */
const fs = require('fs'), path = require('path');
const CAT = path.join(__dirname, '..', 'catalog', 'catalog.json');
const OUT = path.join(__dirname, '..', 'plugin', 'divi5-builder', 'inc', 'blocks-text-fields.php');
if (!fs.existsSync(CAT)) { console.error('ERROR: no catalog/catalog.json. Run: node scripts/catalog.js build <path-to-Divi-theme-folder>'); process.exit(1); }
const cat = JSON.parse(fs.readFileSync(CAT, 'utf8'));
const DENY_EL = new Set(['redirect', 'number', 'barProgress']);
const DENY_LABEL = /URL|Link|Percent|Count|Class|ID/;
const DENY_COMPONENT = new Set(['divi/code', 'divi/map', 'divi/textarea']);
const map = {};
for (const name of Object.keys(cat.modules || {}).sort()) {
  const m = cat.modules[name]; const els = new Set();
  for (const [el, e] of Object.entries(m.elements || {})) {
    if (DENY_EL.has(el) || (name === 'divi/post-filter-item' && el === 'label')) continue;
    for (const f of e.fields || []) {
      if (f.path !== el + '.innerContent' || f.hidden || f.dynamic !== 'text') continue;
      if (DENY_LABEL.test(f.label || '') || DENY_COMPONENT.has(f.component)) continue;
      els.add(el);
    }
  }
  if (els.size) map[name] = [...els].sort();
}
const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const lines = Object.keys(map).map((n) => `\t\t${q(n)} => array( ${map[n].map(q).join(', ')} ),`);
const php = `<?php
/**
 * GENERATED by scripts/gen-text-fields.js from catalog/catalog.json (Divi ${cat.diviVersion}). Do not edit by hand.
 * To regenerate after a new Divi: node scripts/catalog.js build <path-to-Divi-theme-folder>, then
 * node scripts/gen-text-fields.js, and commit this file (the blocks test checks it matches the catalogue).
 *
 * Module => the elements whose <element>.innerContent the catalogue marks as visitor text (dynamic content of type
 * "text"), less a denylist (redirect, number, barProgress, post-filter-item label, labels with URL, Link, Percent,
 * Count, Class or ID, editors divi/code, divi/map, divi/textarea). inc/blocks.php adds its hand list to this.
 * This file only defines a function.
 */
if ( ! defined( 'ABSPATH' ) ) { exit; }

if ( ! function_exists( 'd5b_blocks_text_fields_generated' ) ) {
	function d5b_blocks_text_fields_generated() {
		return array(
${lines.join('\n')}
		);
	}
}
`;
if (process.argv.includes('--stdout')) process.stdout.write(php);
else { fs.writeFileSync(OUT, php); console.log(`${Object.keys(map).length} modules -> ${OUT}`); }
